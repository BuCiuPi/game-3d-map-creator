"""Write one prefabs.md table per prefab category of an imported asset pack.

Usage: python -I tools/assets/gen_prefab_tables.py <pack-root> <docs-out> [scene]

  pack-root  folder holding Prefabs/, e.g. "Assets/EmaceArt/Slavic World Free"
  docs-out   folder receiving <Category>/prefabs.md, e.g. docs/assets/EmaceArt-SlavicWorldFree
  scene      optional .unity path (relative to pack-root) to count prefab instances

Only prefabs.md is written; each category's README.md is hand-written and never touched.
Size is the LODGroup m_Size: the largest dimension in meters, approximate.
"""
import collections
import glob
import os
import re
import sys

ROOT_CATEGORY = "Rooms"


def read(path):
    with open(path, encoding="utf8", errors="ignore") as f:
        return f.read()


def collider(text):
    if "!u!64 " in text:
        return "Mesh"
    if "!u!65 " in text:
        return "Box"
    return "-"


def main():
    pack, out = sys.argv[1], sys.argv[2]
    scene = sys.argv[3] if len(sys.argv) > 3 else None
    prefab_root = os.path.join(pack, "Prefabs")

    instances = collections.Counter()
    if scene:
        for m in re.finditer(r"m_SourcePrefab: \{fileID: \d+, guid: (\w+)", read(os.path.join(pack, scene))):
            instances[m.group(1)] += 1

    cats = collections.defaultdict(list)
    for f in sorted(glob.glob(os.path.join(prefab_root, "**", "*.prefab"), recursive=True)):
        rel = os.path.relpath(f, prefab_root).replace(os.sep, "/")
        parts = rel.split("/")
        cat = parts[0] if len(parts) > 1 else ROOT_CATEGORY
        sub = "/".join(parts[1:-1]) or "-"
        text = read(f)
        guid = re.search(r"guid: (\w+)", read(f + ".meta")).group(1)
        size = re.search(r"m_Size: ([\d.]+)", text)
        lods = len(re.findall(r"m_Name: .* LOD\d", text))
        cats[cat].append((sub, parts[-1][:-len(".prefab")], float(size.group(1)) if size else None,
                          collider(text), lods, instances.get(guid, 0), rel))

    for cat, rows in sorted(cats.items()):
        d = os.path.join(out, cat)
        os.makedirs(d, exist_ok=True)
        lines = [f"# {cat}: prefabs", "",
                 f"Generated by `tools/assets/gen_prefab_tables.py`; do not edit by hand. {len(rows)} prefabs.",
                 "Size = LODGroup `m_Size` in meters (largest dimension, approximate). "
                 "Collider = root collider type. In scene = instances in the demo scene.", "",
                 "| Subgroup | Prefab | Size (m) | Collider | LODs | In scene |",
                 "| --- | --- | --- | --- | --- | --- |"]
        for sub, name, size, col, lods, inst, _ in sorted(rows):
            lines.append(f"| {sub} | `{name}` | {'%.1f' % size if size else '-'} | {col} | {lods or '-'} | {inst or '-'} |")
        with open(os.path.join(d, "prefabs.md"), "w", encoding="utf8", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
        print(cat, len(rows))


if __name__ == "__main__":
    main()
