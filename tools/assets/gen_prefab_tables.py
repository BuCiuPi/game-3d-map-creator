"""Write one knowledge card per prefab of an imported asset pack.

Usage: python -I tools/assets/gen_prefab_tables.py <pack-root> <docs-out> [scene]

  pack-root  folder holding Prefabs/, e.g. "Assets/EmaceArt/Slavic World Free"
  docs-out   folder receiving the cards, e.g. docs/assets/EmaceArt-SlavicWorldFree
  scene      optional .unity path (relative to pack-root) to count prefab instances

Output mirrors Prefabs/: <Category>/<Subgroup>/<Prefab>.md. Prefabs directly in
Prefabs/ go to the "Rooms" category. Each card's generated block is rewritten on
every run; everything below the "## Notes" heading is kept. Each category
README.md gets its prefab list rewritten between the PREFAB-INDEX markers; the
rest of the README is hand-written and kept.
Size is the LODGroup m_Size: the largest dimension in meters, approximate.
"""
import collections
import glob
import os
import re
import sys

ROOT_CATEGORY = "Rooms"
NOTES = "## Notes"
INDEX_START = "<!-- PREFAB-INDEX:START (generated) -->"
INDEX_END = "<!-- PREFAB-INDEX:END -->"


def read(path):
    with open(path, encoding="utf8", errors="ignore") as f:
        return f.read()


def write(path, text):
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write(text)


def collider(text):
    if "!u!64 " in text:
        return "Mesh"
    if "!u!65 " in text:
        return "Box"
    return "none"


def guid_map(pack):
    out = {}
    for meta in glob.glob(os.path.join(pack, "**", "*.meta"), recursive=True):
        g = re.search(r"guid: (\w+)", read(meta))
        if g:
            out[g.group(1)] = os.path.relpath(meta[:-5], pack).replace(os.sep, "/")
    return out


def card(name, rel, guid, sub, size, col, lods, meshes, materials, nested, inst, pack_label):
    lines = [
        f"# {name}",
        "",
        "Generated by `tools/assets/gen_prefab_tables.py`: edit only below the Notes heading.",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Pack | {pack_label} |",
        f"| Path | `Prefabs/{rel}` |",
        f"| GUID | `{guid}` |",
        f"| Subgroup | {sub} |",
        f"| Size (m) | {'%.1f' % size if size else 'unknown (no LOD group)'} |",
        f"| Collider | {col} |",
        f"| LODs | {lods or 'none'} |",
        f"| Meshes | {', '.join(f'`{m}`' for m in meshes) or 'none found'} |",
        f"| Materials | {', '.join(f'`{m}`' for m in materials) or 'none found'} |",
        f"| Nested prefabs | {', '.join(f'`{m}`' for m in nested) or 'none'} |",
        f"| In demo scene | {inst} |",
        "",
        "",
    ]
    return "\n".join(lines)


def main():
    pack, out = sys.argv[1], sys.argv[2]
    scene = sys.argv[3] if len(sys.argv) > 3 else None
    pack_label = os.path.basename(os.path.normpath(out))
    prefab_root = os.path.join(pack, "Prefabs")
    guids = guid_map(pack)

    instances = collections.Counter()
    if scene:
        for m in re.finditer(r"m_SourcePrefab: \{fileID: \d+, guid: (\w+)", read(os.path.join(pack, scene))):
            instances[m.group(1)] += 1

    index = collections.defaultdict(list)
    for f in sorted(glob.glob(os.path.join(prefab_root, "**", "*.prefab"), recursive=True)):
        rel = os.path.relpath(f, prefab_root).replace(os.sep, "/")
        parts = rel.split("/")
        cat = parts[0] if len(parts) > 1 else ROOT_CATEGORY
        sub_parts = parts[1:-1]
        name = parts[-1][:-len(".prefab")]
        text = read(f)
        guid = re.search(r"guid: (\w+)", read(f + ".meta")).group(1)
        size = re.search(r"m_Size: ([\d.]+)", text)
        size = float(size.group(1)) if size else None
        lods = len(re.findall(r"m_Name: .* LOD\d", text))
        refs = [guids.get(g, "") for g in re.findall(r"guid: (\w{32}), type: 3", text)]
        meshes = sorted({os.path.basename(r) for r in refs if r.lower().endswith(".fbx")})
        nested = sorted({os.path.basename(r)[:-len(".prefab")] for r in refs if r.endswith(".prefab")})
        mats = sorted({os.path.basename(guids.get(g, "")) for g in re.findall(r"guid: (\w{32}), type: 2", text)
                       if guids.get(g, "").endswith(".mat")})

        d = os.path.join(out, cat, *sub_parts)
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, name + ".md")
        notes = f"{NOTES}\n\nTODO: hand-written usage notes.\n"
        if os.path.exists(path):
            old = read(path)
            if NOTES in old:
                notes = old[old.index(NOTES):]
        body = card(name, rel, guid, "/".join(sub_parts) or "-", size, collider(text), lods, meshes, mats, nested,
                    instances.get(guid, 0), pack_label)
        write(path, body + notes)
        index[cat].append(("/".join(sub_parts), name, size, instances.get(guid, 0)))

    for cat, rows in sorted(index.items()):
        lines = [INDEX_START, "", f"**{len(rows)} prefabs**, one card each.", "",
                 "| Subgroup | Prefab | Size (m) | In scene |", "| --- | --- | --- | --- |"]
        for sub, name, size, inst in sorted(rows):
            link = "/".join(p for p in (sub, name + ".md") if p).replace(" ", "%20")
            lines.append(f"| {sub or '-'} | [{name}]({link}) | {'%.1f' % size if size else '-'} | {inst or '-'} |")
        lines += ["", INDEX_END]
        block = "\n".join(lines)
        readme = os.path.join(out, cat, "README.md")
        text = read(readme) if os.path.exists(readme) else f"# {cat}\n\nTODO: hand-written overview.\n"
        count = f"**Prefabs: {len(rows)}**"
        head, _, rest = text.partition("\n")
        rest = re.sub(r"\A\n\*\*Prefabs: \d+\*\*\n", "", rest)
        text = f"{head}\n\n{count}\n{rest}"
        if INDEX_START in text:
            text = text[:text.index(INDEX_START)] + block + text[text.index(INDEX_END) + len(INDEX_END):]
        else:
            text = text.rstrip("\n") + "\n\n## Prefabs\n\n" + block + "\n"
        write(readme, text)
        print(cat, len(rows))


if __name__ == "__main__":
    main()
